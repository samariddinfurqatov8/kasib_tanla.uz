import type { SeedCategoryWithTest, SeedOption, SeedQuestion } from './types.ts';

function mcq(
  orderIndex: number,
  difficulty: 'easy' | 'medium' | 'hard',
  questionType: 'knowledge_mcq' | 'cognitive_mcq',
  skillDimension: string,
  promptUz: string,
  promptRu: string,
  promptEn: string,
  options: [
    [string, string, string, boolean?],
    [string, string, string, boolean?],
    [string, string, string, boolean?],
    [string, string, string, boolean?]
  ],
  explanationUz: string,
  explanationRu: string,
  explanationEn: string
): SeedQuestion {
  const keys: ('A' | 'B' | 'C' | 'D')[] = ['A', 'B', 'C', 'D'];
  const mappedOptions: SeedOption[] = options.map((opt, idx) => ({
    optionKey: keys[idx],
    textUz: opt[0],
    textRu: opt[1],
    textEn: opt[2],
    isCorrect: Boolean(opt[3]),
    scoreWeight: opt[3] ? 1 : 0,
  }));
  return {
    orderIndex,
    questionType,
    difficulty,
    skillDimension,
    promptUz,
    promptRu,
    promptEn,
    explanationUz,
    explanationRu,
    explanationEn,
    maxScore: 1,
    options: mappedOptions,
  };
}

