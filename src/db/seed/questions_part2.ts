import type { SeedCategoryWithTest, SeedOption, SeedQuestion } from './types.ts';

function mcq(
  orderIndex: number,
  difficulty: 'easy' | 'medium' | 'hard',
  questionType: 'knowledge_mcq' | 'cognitive_mcq',
  skillDimension: string,
  promptUz: string,
  promptRu: string,
  promptEn: string,
  options: [
    [string, string, string, boolean?],
    [string, string, string, boolean?],
    [string, string, string, boolean?],
    [string, string, string, boolean?]
  ],
  explanationUz: string,
  explanationRu: string,
  explanationEn: string
): SeedQuestion {
  const keys: ('A' | 'B' | 'C' | 'D')[] = ['A', 'B', 'C', 'D'];
  return {
    orderIndex,
    questionType,
    difficulty,
    skillDimension,
    promptUz,
    promptRu,
    promptEn,
    explanationUz,
    explanationRu,
    explanationEn,
    maxScore: 1,
    options: options.map((opt, idx) => ({
      optionKey: keys[idx],
      textUz: opt[0],
      textRu: opt[1],
      textEn: opt[2],
      isCorrect: Boolean(opt[3]),
      scoreWeight: opt[3] ? 1 : 0,
    })),
  };
}

function rubricQ(
  orderIndex: number,
  difficulty: 'easy' | 'medium' | 'hard',
  questionType: 'cognitive_mcq' | 'rubric_interest',
  skillDimension: string,
  promptUz: string,
  promptRu: string,
  promptEn: string,
  options: Array<{
    uz: string;
    ru: string;
    en: string;
    scoreWeight: number;
    traitTag: string;
    isCorrect?: boolean;
  }>,
  explanationUz: string,
  explanationRu: string,
  explanationEn: string
): SeedQuestion {
  const keys: ('A' | 'B' | 'C' | 'D')[] = ['A', 'B', 'C', 'D'];
  const maxScore = Math.max(...options.map((o) => o.scoreWeight));
  const mapped: SeedOption[] = options.map((o, idx) => ({
    optionKey: keys[idx],
    textUz: o.uz,
    textRu: o.ru,
    textEn: o.en,
    isCorrect: Boolean(o.isCorrect),
    scoreWeight: o.scoreWeight,
    traitTag: o.traitTag,
  }));
  return {
    orderIndex,
    questionType,
    difficulty,
    skillDimension,
    promptUz,
    promptRu,
    promptEn,
    explanationUz,
    explanationRu,
    explanationEn,
    maxScore,
    options: mapped,
  };
}

