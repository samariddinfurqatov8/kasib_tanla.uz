export function pickLang<T extends Record<string, unknown>>(
  obj: T | null | undefined,
  baseKey: string,
  lang: Language
): string {
  if (!obj) return '';
  const suffix = lang === 'ru' ? 'Ru' : lang === 'en' ? 'En' : 'Uz';
  const val = obj[`${baseKey}${suffix}`] ?? obj[`${baseKey}Uz`];
  return typeof val === 'string' ? val : '';
}

export function formatSkillName(skillKey: string, lang: Language): string {
  const dict = TRANSLATIONS[lang].skillNames as Record<string, string>;
  return dict[skillKey] ?? skillKey;
}

export function formatMeasurementType(type: MeasurementType | string, lang: Language): string {
  const dict = TRANSLATIONS[lang].measurementLabels as Record<string, string>;
  return dict[type] ?? type;
}

export function formatDateShort(iso: string | Date, lang: Language): string {
  const d = typeof iso === 'string' ? new Date(iso) : iso;
  const locale = lang === 'ru' ? 'ru-RU' : lang === 'en' ? 'en-US' : 'uz-UZ';
  return d.toLocaleDateString(locale, {
    year: 'numeric',
    month: 'short',
    day: 'numeric',
  });
}
